import { chromium } from 'playwright'
const nav = await chromium.launch()
const page = await nav.newPage({ viewport: { width: 1440, height: 900 } })
page.on('pageerror', (e) => console.log('[PAGEERROR]', e.message))
page.on('console', (m) => { if (m.type()==='error') console.log('[console.error]', m.text().slice(0,200)) })
await page.goto('http://localhost:5173/app/', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Réglages' }).click()
await page.getByRole('button', { name: 'Importer le catalogue' }).click()
await page.waitForFunction(() => /entrées importées/.test(document.body.innerText), null, { timeout: 120000 })
await page.getByRole('button', { name: 'Rechercher' }).click()
await page.waitForTimeout(4000)
console.log('--- via la navigation ---')
console.log(JSON.stringify(await page.evaluate(() => document.querySelector('main')?.innerText?.slice(0,200) ?? '(main vide)')))
await page.getByRole('button', { name: 'Accueil' }).click()
await page.waitForTimeout(1500)
const champ = page.locator('main input').first()
await champ.fill('tf1'); await champ.press('Enter')
await page.waitForTimeout(4000)
console.log('--- apres Entree depuis l Accueil ---')
console.log(JSON.stringify(await page.evaluate(() => document.querySelector('main')?.innerText?.slice(0,200) ?? '(main vide)')))
console.log('nb input dans main:', await page.evaluate(() => document.querySelectorAll('main input').length))
await nav.close()
