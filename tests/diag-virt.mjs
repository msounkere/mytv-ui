import { chromium } from 'playwright'
const nav = await chromium.launch()
const page = await nav.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto('http://localhost:5173/app/', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Réglages' }).click()
await page.getByRole('button', { name: 'Importer le catalogue' }).click()
await page.waitForFunction(() => /entrées importées/.test(document.body.innerText), null, { timeout: 120000 })
await page.getByRole('button', { name: 'Parcours' }).click()
await page.waitForTimeout(2000)
const d = await page.evaluate(() => [...document.querySelectorAll('[data-diag]')].map(e => e.dataset.diag))
console.log('--- etat du virtualiseur ---')
d.forEach(x => console.log(' ', x))
// Provoquer un scroll : si les items apparaissent, c'est la mesure initiale qui manque.
await page.evaluate(() => { const a = document.querySelector('aside'); const s = a?.lastElementChild; if (s) s.scrollTop = 100 })
await page.waitForTimeout(1200)
const d2 = await page.evaluate(() => [...document.querySelectorAll('[data-diag]')].map(e => e.dataset.diag))
console.log('--- apres un scroll de 100px ---')
d2.forEach(x => console.log(' ', x))
console.log('boutons categories:', await page.evaluate(() => document.querySelectorAll('aside button[title]').length))
await nav.close()
