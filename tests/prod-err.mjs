import { chromium } from 'playwright'
const nav = await chromium.launch({ args: ['--host-resolver-rules=MAP mytv.msocasa.com 192.168.50.6'], ignoreHTTPSErrors: true })
const page = await nav.newPage({ viewport: { width: 1440, height: 900 }, ignoreHTTPSErrors: true })
page.on('pageerror', e => console.log('[PAGEERROR]', e.message))
page.on('console', m => { if (m.type()==='error') console.log('[console]', m.text().slice(0,300)) })
page.on('requestfailed', r => console.log('[REQ ECHEC]', r.url().slice(0,110), '—', r.failure()?.errorText))
page.on('response', r => { if (r.status() >= 400) console.log('[HTTP', r.status(), ']', r.url().slice(0,110)) })
await page.goto('https://mytv.msocasa.com/app/', { waitUntil: 'networkidle', timeout: 60000 })
await page.waitForTimeout(3000)
console.log('--- texte affiché ---')
console.log(await page.evaluate(() => document.body.innerText.slice(0, 900)))
await nav.close()
