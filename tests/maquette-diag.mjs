import { chromium } from 'playwright'
const nav = await chromium.launch()
const page = await nav.newPage({ viewport: { width: 390, height: 844 } })
page.on('console', (m) => console.log('[console]', m.type(), m.text().slice(0, 160)))
page.on('pageerror', (e) => console.log('[erreur]', e.message.slice(0, 200)))
page.on('requestfailed', (r) => console.log('[echec]', r.url().slice(-70), r.failure()?.errorText))
page.on('response', (r) => { if (r.status() >= 400) console.log('[http]', r.status(), r.url().slice(-70)) })
await page.goto('http://127.0.0.1:8777/Lecteur%20IPTV.dc.html?ecran=direct', { waitUntil: 'load', timeout: 60000 })
await page.waitForTimeout(6000)
console.log('texte :', (await page.evaluate(() => document.body.innerText)).length, 'car.')
await nav.close()
